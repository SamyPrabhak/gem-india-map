const normalize = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/\bislands?\b/g, "")
    .replace(/[^a-z]/g, "");

const index = new Map(jewelryPieces.map((p) => [normalize(p.state), p]));

export function getJewelryPiece(stateName: string): JewelryPiece | undefined {
  return index.get(normalize(stateName));
}
